/** เขียนไฟล์ด้วย fs ของ Node โดยตรง เพื่อรองรับชื่อไฟล์ภาษาไทย */
function saveWorkbook(workbook, fileName) {
  const buffer = XLSX.write(workbook, { bookType: 'xlsx', type: 'buffer', compression: true });
  writeFileSync(resolve(outDir, fileName), buffer);
}

function saveText(fileName, content) {
  writeFileSync(resolve(outDir, fileName), content, 'utf8');
}

